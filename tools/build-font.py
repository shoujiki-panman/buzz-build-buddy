"""Build the Japanese UI font subset.

UIKit draws text from an MSDF atlas, so every glyph must be known up front.
This script collects the characters used in src/content and public/ui, adds
ASCII and kana, and writes:

  public/fonts/buzz-jp.ttf        Noto Sans JP (wght 500), subset to those glyphs
  src/generated/jp-charset.ts     the same characters, for TTFLoader

Run after changing any on-screen text:  python3 tools/build-font.py
Source font: fonts-src/NotoSansJP-VF.ttf (google/fonts, SIL OFL 1.1). Download:
  curl -L -o fonts-src/NotoSansJP-VF.ttf "https://github.com/google/fonts/raw/main/ofl/notosansjp/NotoSansJP%5Bwght%5D.ttf"
The licence travels with the subset as public/fonts/OFL.txt.
"""

from pathlib import Path
import json

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SOURCE_FONT = ROOT / "fonts-src" / "NotoSansJP-VF.ttf"
OUT_FONT = ROOT / "public" / "fonts" / "buzz-jp.ttf"
OUT_CHARSET = ROOT / "src" / "generated" / "jp-charset.ts"
WEIGHT = 500

TEXT_SOURCES = [
    *sorted((ROOT / "src" / "content").glob("*.ts")),
    *sorted((ROOT / "public" / "ui").glob("*.uikitml")),
]

BASE_RANGES = [
    (0x20, 0x7E),  # ASCII
    (0x3001, 0x3002),  # 、。
    (0x300C, 0x300F),  # 「」『』
    (0x3041, 0x3096),  # hiragana
    (0x30A1, 0x30FA),  # katakana
    (0x30FC, 0x30FC),  # ー
    (0xFF01, 0xFF5E),  # fullwidth ASCII (＋ etc.)
]


def collect_chars() -> set[str]:
    chars: set[str] = set()
    for start, end in BASE_RANGES:
        chars.update(chr(c) for c in range(start, end + 1))
    for path in TEXT_SOURCES:
        chars.update(path.read_text(encoding="utf-8"))
    return {c for c in chars if c.isprintable()}


def main() -> None:
    font = TTFont(SOURCE_FONT)
    cmap = font.getBestCmap()
    wanted = collect_chars()
    present = sorted(c for c in wanted if ord(c) in cmap)
    missing = sorted(c for c in wanted if ord(c) not in cmap)

    static = instancer.instantiateVariableFont(font, {"wght": WEIGHT})
    options = subset.Options()
    options.notdef_outline = True
    options.name_IDs = ["*"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(text="".join(present))
    subsetter.subset(static)

    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    static.save(OUT_FONT)

    charset = "".join(present)
    OUT_CHARSET.parent.mkdir(parents=True, exist_ok=True)
    OUT_CHARSET.write_text(
        "// Generated by tools/build-font.py. Do not edit.\n"
        f"export const JP_CHARSET = {json.dumps(charset, ensure_ascii=False)};\n",
        encoding="utf-8",
    )

    size_kb = OUT_FONT.stat().st_size / 1024
    print(f"glyphs: {len(present)}  font: {size_kb:.0f} KB  missing: {''.join(missing)!r}")


if __name__ == "__main__":
    main()
